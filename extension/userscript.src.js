  // A mutation is "ours" when it happens inside the overlay or only adds/removes our own nodes (badges): never re-scan for those.
  function isOursNode(n) {
    if (n.nodeType === 1) return n.hasAttribute("data-fdc-ignore") || !!n.closest("[data-fdc-ignore]");
    if (n.nodeType === 3) return !!(n.parentElement && n.parentElement.closest("[data-fdc-ignore]"));
    return true;
  }
  function onlyOurs(m) {
    if (isOursNode(m.target)) return true;
    if (m.type !== "childList") return false;
    const nodes = [...m.addedNodes, ...m.removedNodes];
    return nodes.length > 0 && nodes.every(isOursNode);
  }

  function boot() {
    scan();
    setTimeout(() => maybeAutoSync("load"), SEASON.autoSyncDelayMs);
    document.addEventListener("visibilitychange", () => {
      if (document.visibilityState === "visible") {
        maybeAutoSync("visible");
        state.returnedAt = Date.now();
        state.lastKey = ""; // back in front: rescan and send right away
        scan();
        alertTick();
        setTimeout(alertTick, APP.returnAlertMs + 100);
        void fetchRec(true);
      } else {
        state.lastKey = "";
        scan(); // tell the app the page is going to the background
      }
    });
    const mo = new MutationObserver((muts) => {
      if (muts.every(onlyOurs)) return;
      proj.lastMutationAt = Date.now();
      schedule();
      scheduleBadges();
    });
    mo.observe(document.documentElement, { childList: true, subtree: true, characterData: true });
    setInterval(scan, APP.intervalMs);
    setInterval(() => void fetchRec(false), APP.recommendMs);
    setInterval(applyBadges, APP.recommendMs); // safety net if Yahoo drops our badge without another DOM change we notice
    setInterval(render, 1000);
    setInterval(alertTick, 1000);
    setInterval(renderSeason, 1000);
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", boot);
  else boot();
