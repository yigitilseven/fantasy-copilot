  /** POSTs queued rows in batches of <= projBatch. Returns the summed server summary, or null on failure (rows stay queued). */
  async function flushProjections() {
    if (proj.flushing) return null;
    proj.flushing = true;
    const sum = { received: 0, matched: 0, created: 0 };
    try {
      while (proj.queue.size) {
        const batch = [...proj.queue.values()].slice(0, APP.projBatch);
        const r = await request("POST", APP.projectionsPath, { season: "2026-27", view: "proj", rows: batch.map((b) => b.r) });
        if (r.status !== 200) {
          proj.failedAt = Date.now();
          const b = json(r);
          proj.status = "Projections not saved: " + ((b && b.error) || "server answered " + r.status);
          return null;
        }
        const b = json(r);
        for (const it of batch) {
          proj.seen.set(it.r.yahooId, it.key);
          proj.queue.delete(it.r.yahooId);
        }
        proj.sentTotal += batch.length;
        sum.received += b.received || batch.length;
        sum.matched += b.matched || 0;
        sum.created += b.created || 0;
      }
      return sum;
    } catch {
      proj.failedAt = Date.now();
      proj.status = "Projections not saved: app not reachable";
      return null;
    } finally {
      proj.flushing = false;
      render();
    }
  }

