  async function fetchRec(force) {
    if (!els) return;
    if (rec.inflight && !force && Date.now() - rec.startedAt < APP.requestTimeoutMs) return;
    const seq = ++rec.seq; // stale-response guard: only the newest request may update the UI
    rec.inflight = true;
    rec.startedAt = Date.now();
    const id = state.draftId != null ? state.draftId : "active";
    try {
      const r = await request("GET", "/api/draft/" + id + "/recommendations?limit=10");
      if (seq !== rec.seq) return;
      state.connected = true;
      if (r.status === 200) {
        const d = json(r);
        if (d && Array.isArray(d.top)) {
          const key = JSON.stringify({ ...d, generatedAt: 0, simMs: 0 });
          rec.at = Date.now();
          rec.err = "";
          if (key !== rec.key) {
            rec.key = key;
            rec.data = d;
            rec.boardIndex = buildBoardIndex(d.board);
            renderRec();
            applyBadges();
          }
        } else rec.err = "Unexpected recommendations response";
      } else rec.err = r.status === 404 ? "No active draft in the app" : "Recommendations unavailable (" + r.status + ")";
    } catch {
      if (seq !== rec.seq) return;
      rec.err = "down";
    } finally {
      if (seq === rec.seq) rec.inflight = false;
    }
    render();
  }

  async function patchStrategy(body) {
    const id = (rec.data && rec.data.draftId) != null ? rec.data.draftId : state.draftId;
    if (id == null) return;
    rec.patching = true;
    render();
    try {
      const r = await request("PATCH", "/api/draft/" + id + "/strategy", body);
      rec.err = r.status >= 200 && r.status < 300 ? "" : "Strategy update failed (" + r.status + ")";
    } catch {
      rec.err = "down";
    }
    rec.patching = false;
    await fetchRec(true);
  }

