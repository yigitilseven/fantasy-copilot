  // ---- autonomous league sync: same-origin GETs of pages you could open yourself (paced, single flight, read-only), parsed here, posted to the app

  const seasonLock = {
    id: Math.random().toString(36).slice(2),
    read() {
      try {
        return JSON.parse(localStorage.getItem(SEASON.lockKey) || "null");
      } catch {
        return null;
      }
    },
    write(v) {
      try {
        if (v) localStorage.setItem(SEASON.lockKey, JSON.stringify(v));
        else localStorage.removeItem(SEASON.lockKey);
      } catch {
        /* storage blocked: single flight within this tab only */
      }
    },
    acquire() {
      const cur = seasonLock.read();
      if (cur && cur.id !== seasonLock.id && Date.now() - cur.at < SYNC_DEFAULTS.lockTtlMs) return false;
      seasonLock.write({ id: seasonLock.id, at: Date.now() });
      const back = seasonLock.read();
      return !back || back.id === seasonLock.id;
    },
    touch() {
      const cur = seasonLock.read();
      if (!cur || cur.id === seasonLock.id) seasonLock.write({ id: seasonLock.id, at: Date.now() });
    },
    release() {
      const cur = seasonLock.read();
      if (cur && cur.id === seasonLock.id) seasonLock.write(null);
    },
  };

  async function startSync(trigger) {
    if (sstate.sync.running || window !== window.top) return;
    const sp = parseSeasonUrl(location.href);
    if (!sp.leagueId || sp.kind === "draft") return;
    await seasonStatus(true);
    if (!sstate.status || !sstate.status.league) {
      sstate.sync.msg = sstate.statusErr || "No season league in the app yet";
      renderSeason();
      return;
    }
    sstate.sync.running = true;
    sstate.sync.trigger = trigger;
    sstate.sync.msg = "";
    sls.set({ lastAttemptAt: Date.now() });
    ensureSeasonOverlay();
    renderSeason();
    const env = {
      origin: location.origin,
      doc: document,
      href: location.href,
      expectedTeams: sstate.status.league.teams || 14,
      // light runs skip the free-agent crawl while the stored list is fresh; the browser worker sets __FDC_SYNC_FULL for a manual refresh
      lastFaAt: sstate.status.freeAgentsAt || null,
      fullSync: window.__FDC_SYNC_FULL === true || trigger === "button",
      fetchPage: async (url) => {
        const r = await fetch(url, { method: "GET", credentials: "same-origin", cache: "no-store", redirect: "follow", headers: { Accept: "text/html" } });
        return { status: r.status, url: r.url, text: await r.text() };
      },
      parseHtml: (text) => new DOMParser().parseFromString(text, "text/html"),
      post: async (path, body) => {
        const r = await request("POST", path, body);
        return { status: r.status, body: json(r) };
      },
      sleep,
      now: () => Date.now(),
      rand: Math.random,
      lock: seasonLock,
      samples: { allowed: sampleStore.allowed, mark: sampleStore.mark, send: sendSample },
      onProgress: (rep) => {
        seasonLock.touch();
        sstate.sync.report = rep;
        renderSeason();
      },
    };
    try {
      // window.__FDC_SYNC_PACE_MS is for the e2e tests only (like __FDC_ORIGIN); real use keeps the polite defaults.
      const rep = await runLeagueSync(env, typeof window.__FDC_SYNC_PACE_MS === "number" ? { paceMs: window.__FDC_SYNC_PACE_MS, jitterMs: 0 } : {});
      sstate.sync.report = rep;
      if (rep.skipped) sstate.sync.msg = "Sync skipped: " + rep.skipped;
      else if (rep.complete) sls.set({ lastFullAt: Date.now() });
      if (rep.stopped) sstate.sync.msg = "Sync stopped: " + rep.stopped;
    } catch (e) {
      sstate.sync.msg = "Sync failed: " + ((e && e.message) || e);
    }
    sstate.sync.running = false;
    await seasonStatus(true);
    renderSeason();
  }

