  // ------------------------------------------------------------------ transport

  /** GM.xmlHttpRequest (bypasses page CORS and mixed content) with a fetch fallback. Resolves { status, text } or rejects. */
  function request(method, path, bodyObj) {
    const url = APP.origin + path;
    const data = bodyObj === undefined ? undefined : JSON.stringify(bodyObj);
    const headers = data === undefined ? {} : { "Content-Type": "application/json" };
    const viaFetch = () =>
      fetch(url, { method, headers, body: data, mode: "cors", cache: "no-store" }).then((r) => r.text().then((text) => ({ status: r.status, text })));
    const gm =
      typeof GM !== "undefined" && GM && typeof GM.xmlHttpRequest === "function"
        ? GM.xmlHttpRequest.bind(GM)
        : typeof GM_xmlhttpRequest === "function"
          ? GM_xmlhttpRequest
          : null;
    if (!gm) return viaFetch();
    return new Promise((resolve, reject) => {
      let settled = false;
      const done = (fn, v) => {
        if (!settled) {
          settled = true;
          fn(v);
        }
      };
      try {
        const ret = gm({
          method,
          url,
          headers,
          data,
          timeout: APP.requestTimeoutMs,
          onload: (r) => done(resolve, { status: r.status, text: r.responseText || "" }),
          onerror: () => done(reject, new Error("network")),
          ontimeout: () => done(reject, new Error("timeout")),
        });
        if (ret && typeof ret.then === "function") ret.then((r) => r && r.status !== undefined && done(resolve, { status: r.status, text: r.responseText || r.response || "" }), () => done(reject, new Error("network")));
      } catch {
        done(reject, new Error("gm-failed"));
      }
    }).catch((e) => (e && e.message === "gm-failed" ? viaFetch() : Promise.reject(e)));
  }

  const json = (r) => {
    try {
      return JSON.parse(r.text);
    } catch {
      return {};
    }
  };

  // ------------------------------------------------------------------ state

  const state = {
    paused: false,
    connected: null, // null = unknown, true/false after the first request
    draftId: null,
    teams: null,
    draftCheckedAt: 0,
    parsed: 0,
    method: "none",
    lastKey: "",
    lastSendAt: 0,
    sending: false,
    needsRetry: false,
    lastPickSent: 0,
    lastError: "",
    info: "",
    snapshot: "",
    postdraftKeys: {}, // section -> JSON of what the server already has (standings:<view> / board / results)
    postdraftBusy: false,
    lastDraftId: null, // the last active draft the app reported (still the target once it completed)
    headerPicks: new Map(), // pick -> { pick, playerName, positions?, nbaTeam? } seen in the always-visible header ("Last: ...")
    boardPicks: new Map(), // pick -> board-tab pick (league rooms without a Picks feed)
    boardSeenAt: 0,
    panel: "n/a", // "picks" | "hidden" | "n/a" (see panelState in parser.js)
    hiddenSince: null,
    returnedAt: 0,
    dismissUntil: 0,
    alertShown: false,
    interacted: false,
    origTitle: null,
  };

  function setError(msg) {
    state.lastError = msg;
    render();
  }

  async function refreshDraft(force) {
    if (!force && state.draftId && Date.now() - state.draftCheckedAt < APP.draftRefreshMs) return true;
    try {
      const r = await request("GET", "/api/draft/active-id");
      state.connected = true;
      state.draftCheckedAt = Date.now();
      if (r.status === 200) {
        const d = json(r);
        if (d.id !== state.draftId) state.lastKey = ""; // new draft: resend everything
        state.draftId = d.id;
        state.lastDraftId = d.id;
        state.teams = d.teams || null;
        return true;
      }
      state.draftId = null;
      setError("No active draft in the app. Open " + APP.origin + "/draft first.");
      return false;
    } catch {
      state.connected = false;
      state.draftId = null;
      setError("Not connected to " + APP.origin.replace(/^https?:\/\//, "") + " (is `pnpm dev` running?)");
      return false;
    }
  }

  async function send(picks) {
    if (state.sending) return;
    state.sending = true;
    try {
      if (!(await refreshDraft(false))) {
        state.needsRetry = true;
        return;
      }
      const extra = {};
      try {
        const rk = draftRoomKey(location.href);
        if (rk) extra.roomKey = rk;
        const ln = parseLeagueName(document);
        if (ln) extra.leagueName = ln;
      } catch {
        /* optional metadata */
      }
      const r = await request("POST", "/api/draft/" + state.draftId + "/external-picks", { source: "yahoo-dom", picks, panel: state.panel, pageVisible: document.visibilityState !== "hidden", ...extra });
      const b = json(r);
      state.connected = true;
      state.lastSendAt = Date.now();
      if (r.status === 200) {
        state.needsRetry = false;
        state.lastError = "";
        state.lastPickSent = b.draft ? b.draft.currentPick - 1 : state.lastPickSent;
        if (b.draft && (!rec.data || b.draft.currentPick !== rec.data.currentPick)) void fetchRec(true);
        const bits = [];
        if (b.ingested) bits.push(b.ingested + " new");
        if (b.mismatches && b.mismatches.length) bits.push(b.mismatches.length + " differ from app (pick " + b.mismatches.map((m) => m.pick).join(",") + ")");
        if (b.corrected) bits.push("re-synced from pick " + b.corrected.fromPick + " to match Yahoo");
        const ar = b.autoResolved || [];
        const guessed = ar.filter((a) => a.resolution === "guessed").map((a) => a.name);
        const added = ar.filter((a) => a.resolution === "placeholder").map((a) => a.name);
        if (guessed.length) bits.push("best guess: " + guessed.join(", "));
        if (added.length) bits.push("added unknown: " + added.join(", "));
        if (ar.some((a) => a.resolution === "unknown")) bits.push("holding skipped picks");
        if (b.stoppedReason === "draft_complete") bits.push("draft complete");
        state.info = bits.join(" · ");
      } else if (r.status === 409 && b.code === "UNMAPPED_PLAYER") {
        state.needsRetry = true; // keep retrying: the user fixes it in the app and we pick up from there
        state.lastPickSent = b.draft ? b.draft.currentPick - 1 : state.lastPickSent;
        state.lastError = 'Unmapped player "' + b.name + '" (pick ' + b.pick + ") - fix in app (top bar > Browser sync).";
      } else if (r.status === 404) {
        state.draftId = null;
        state.needsRetry = true;
        state.lastError = "Draft not found in the app; looking for the active draft.";
      } else {
        state.needsRetry = true;
        state.lastError = (b && b.error) || "Server answered " + r.status;
      }
    } catch {
      state.connected = false;
      state.needsRetry = true;
      state.lastError = "Not connected to " + APP.origin.replace(/^https?:\/\//, "") + " (is `pnpm dev` running?)";
    } finally {
      state.sending = false;
      render();
    }
  }

  // ------------------------------------------------------------------ post-draft capture (Board / Standings / Results)

  // After "Draft Complete", whichever of the Standings (any of its three stat views), Board and Results > Teams tabs is on screen is
  // sent to POST /api/draft/:id/postdraft once (again only when its content changes). Read-only; failures are silent and retried.
  async function postdraftScan(header) {
    if (state.paused || state.postdraftBusy || !(state.draftId || state.lastDraftId) || !header || !header.complete || document.visibilityState === "hidden") return;
    const body = {};
    const keys = {};
    try {
      const st = parseStandings(document);
      if (st.active && st.view !== "unknown" && st.rows.length >= 2) {
        const rows = st.rows.map((r) => {
          const o = { ...r };
          delete o.label;
          return o;
        });
        const k = "standings:" + st.view;
        const key = JSON.stringify(rows);
        if (state.postdraftKeys[k] !== key) {
          body.standings = [{ view: st.view, rows }];
          keys[k] = key;
        }
      }
      const bd = parseBoard(document);
      if (bd.active && bd.picks.length) {
        const payload = { teams: bd.teams, picks: bd.picks.map((p) => ({ pick: p.pick, playerName: p.playerName, nbaTeam: p.nbaTeam, positions: p.positions, teamName: p.teamName })) };
        const key = JSON.stringify(payload);
        if (state.postdraftKeys.board !== key) {
          body.board = payload;
          keys.board = key;
        }
      }
      const rt = parseResultsTeams(document);
      if (rt.picks.length) {
        const key = JSON.stringify(rt.picks);
        if (state.postdraftKeys.results !== key) {
          body.results = { picks: rt.picks };
          keys.results = key;
        }
      }
    } catch {
      return; // layout changed: the live feed path is unaffected
    }
    if (!Object.keys(keys).length) return;
    try {
      const rk = draftRoomKey(location.href);
      if (rk) body.roomKey = rk;
      const ln = parseLeagueName(document);
      if (ln) body.leagueName = ln;
    } catch {
      /* optional */
    }
    state.postdraftBusy = true;
    try {
      const r = await request("POST", "/api/draft/" + (state.draftId || state.lastDraftId) + "/postdraft", body);
      if (r.status === 200) {
        Object.assign(state.postdraftKeys, keys);
        state.info = "post-draft data saved (" + Object.keys(keys).join(", ") + ")";
        render();
      }
    } catch {
      /* retried on the next scan */
    } finally {
      state.postdraftBusy = false;
    }
  }

  // ------------------------------------------------------------------ scanning

  function scan() {
    // Season mode: in-season league pages (/nba/<league>/...) are read by their own module; the draft logic below never runs there.
    const sp = parseSeasonUrl(location.href);
    if (sp.leagueId && sp.kind !== "draft") {
      if (window === window.top) seasonScan(sp);
      return;
    }
    if (state.paused) return;
    let res;
    try {
      res = parseDraftRoom(document, { teams: state.teams });
    } catch (e) {
      state.lastError = "Parser error: " + (e && e.message);
      render();
      return;
    }
    // The header ("Round 13, Pick 182" / "Last: O. Ighodaro (C . PHX)") is visible whatever side panel is open: remember what it
    // shows, so a hidden Picks feed (Queue tab) does not stop the sync. Feed picks win over header picks.
    let header = null;
    try {
      header = parseHeaderState(document);
    } catch {
      /* header layout changed: feed only */
    }
    if (header && header.last) state.headerPicks.set(header.last.pick, header.last);
    // League draft rooms may have no Picks feed (side panel = Queue | Chat). The Board tab lists every pick: read it live too and
    // remember what it showed, so switching back to Players keeps those picks. Order: header < board < feed (feed wins).
    try {
      const bd = parseBoard(document);
      if (bd && bd.active) {
        state.boardSeenAt = Date.now();
        for (const p of bd.picks) state.boardPicks.set(p.pick, p);
      }
    } catch {
      /* board layout changed: feed/header only */
    }
    updatePanel();
    void postdraftScan(header);
    const picks = mergePickLists([...state.headerPicks.values()], [...state.boardPicks.values()], res.picks);
    state.parsed = picks.length;
    state.method = res.method + (res.detail ? ":" + String(res.detail).slice(0, 40) : "") + (picks.length > res.picks.length ? " + header" : "");
    const key = JSON.stringify(picks) + "|" + state.panel + "|" + (document.visibilityState !== "hidden");
    const due = Date.now() - state.lastSendAt >= APP.heartbeatMs;
    // Frames other than the top window only talk once they actually see picks.
    const mute = window !== window.top && !picks.length;
    if (!mute && (key !== state.lastKey || due || state.needsRetry)) {
      state.lastKey = key;
      void send(picks);
    }
    if (res.needsTeams && !state.teams && !mute) void refreshDraft(true);
    if (picks.length || APP.overlayPagePattern.test(location.href)) ensureOverlay();
    passiveProjections();
    autoProjections();
    render();
  }

  let debounce = null;
  function schedule() {
    clearTimeout(debounce);
    debounce = setTimeout(scan, APP.debounceMs);
  }

  // ------------------------------------------------------------------ snapshot (for calibrating selectors)

  function buildSnapshot() {
    const clone = document.documentElement.cloneNode(true);
    for (const n of clone.querySelectorAll("script,style,noscript,svg,link[rel='stylesheet'],[data-fdc-ignore]")) n.remove();
    for (const n of clone.querySelectorAll("[src^='data:'],[style*='data:']")) {
      n.removeAttribute("src");
      n.removeAttribute("style");
    }
    let html = "<!doctype html>\n" + clone.outerHTML;
    if (html.length > APP.snapshotMaxHtml) html = html.slice(0, APP.snapshotMaxHtml) + "\n<!-- truncated -->";
    let frames = "";
    for (const f of document.querySelectorAll("iframe")) {
      try {
        const d = f.contentDocument;
        if (d && d.documentElement) frames += "\n<!-- iframe " + (f.src || "(no src)") + " -->\n" + d.documentElement.outerHTML.replace(/<(script|style|svg)[\s\S]*?<\/\1>/gi, "");
      } catch {
        frames += "\n<!-- cross-origin iframe " + f.src + " -->";
      }
      if (frames.length > APP.snapshotMaxFrames) break;
    }
    const text = (document.body ? textLines(document.body).join("\n") : "").slice(0, APP.snapshotMaxText);
    return { url: location.href, html: html + frames.slice(0, APP.snapshotMaxFrames), text };
  }

  async function sendSnapshot() {
    state.snapshot = "sending snapshot...";
    render();
    try {
      let snap = buildSnapshot();
      let body = JSON.stringify(snap);
      while (body.length > 4800000 && snap.html.length > 100000) {
        snap = { ...snap, html: snap.html.slice(0, Math.floor(snap.html.length / 2)) };
        body = JSON.stringify(snap);
      }
      const r = await request("POST", "/api/debug/draftroom-snapshot", snap);
      const b = json(r);
      state.snapshot = r.status === 201 ? "Snapshot saved: " + String(b.saved).split("/").slice(-1)[0] : "Snapshot failed: " + ((b && b.error) || r.status);
    } catch (e) {
      state.snapshot = "Snapshot failed: " + (e && e.message);
    }
    render();
  }

