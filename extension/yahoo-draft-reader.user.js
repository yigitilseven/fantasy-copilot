  // A mutation is "ours" when it happens inside the overlay or only adds/removes our own nodes (badges): never re-scan for those.
  function isOursNode(n) {
    if (n.nodeType === 1) return n.hasAttribute("data-fdc-ignore") || !!n.closest("[data-fdc-ignore]");
    if (n.nodeType === 3) return !!(n.parentElement && n.parentElement.closest("[data-fdc-ignore]"));
    return true;
  }
  function onlyOurs(m) {
    if (isOursNode(m.target)) return true;
    if (m.type !== "childList") return false;
    const nodes = [...m.addedNodes, ...m.removedNodes];
    return nodes.length > 0 && nodes.every(isOursNode);
  }

