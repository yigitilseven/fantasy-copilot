  function enqueueFa(rows) {
    let added = 0;
    for (const r of rows) {
      if (!r.yahooId && !r.playerName) continue;
      const k = r.yahooId || "n:" + r.playerName;
      const h = JSON.stringify([r.pctOwned, r.injuryTag, r.stats, r.nbaTeam]);
      if (sstate.fa.seen.get(k) === h) continue;
      sstate.fa.seen.set(k, h);
      sstate.fa.queue.push(r);
      added++;
    }
    return added;
  }

  async function flushFa() {
    if (sstate.fa.busy) return;
    sstate.fa.busy = true;
    try {
      while (sstate.fa.queue.length) {
        const batch = sstate.fa.queue.splice(0, SEASON.faBatch);
        try {
          const out = await seasonPost("/api/season/free-agents", { url: location.href, players: slim(batch) });
          sstate.fa.sent += batch.length;
          sstate.fa.msg = "Free agents sent: " + sstate.fa.sent + " rows (pool " + out.poolSize + (out.unmatched.length ? ", " + out.unmatched.length + " unmatched in last batch" : "") + ")";
          sstate.err = "";
        } catch (e) {
          sstate.err = "Free agents not accepted: " + e.message;
          for (const r of batch) sstate.fa.seen.delete(r.yahooId || "n:" + r.playerName); // retry later
          break;
        }
      }
    } finally {
      sstate.fa.busy = false;
    }
    void seasonStatus(true);
  }

