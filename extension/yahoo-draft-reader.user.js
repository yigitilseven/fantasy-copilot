  /** Reads the following pages of the same list with same-origin GETs (read-only, polite). */
  async function crawlFaPages(doc, href) {
    if (!crawlOn() || sstate.crawl.running || document.visibilityState === "hidden") return;
    const u0 = new URL(href);
    u0.searchParams.delete("count");
    const sig = u0.pathname + "?" + [...u0.searchParams.entries()].sort().map((e) => e.join("=")).join("&");
    const crawls = sls.get().crawls || {};
    if (crawls[sig] && Date.now() - crawls[sig] < SEASON.crawlTtlMs) return;
    const queue = findSeasonPageLinks(doc, href);
    if (!queue.length) {
      sls.set({ crawls: { ...crawls, [sig]: Date.now() } });
      return;
    }
    if (!seasonLock.acquire()) return; // a sync (maybe in another tab) is reading pages right now
    sstate.crawl.running = true;
    sstate.crawl.pages = 0;
    sstate.crawl.msg = "";
    const visited = new Set([href]);
    try {
      while (queue.length && sstate.crawl.pages < SEASON.crawlMaxPages) {
        const next = queue.shift();
        if (visited.has(next)) continue;
        visited.add(next);
        await sleep(SEASON.crawlGapMs);
        seasonLock.touch();
        if (!crawlOn()) {
          sstate.crawl.msg = "stopped (toggle off)";
          break;
        }
        const resp = await fetch(next, { method: "GET", credentials: "same-origin", cache: "no-store", headers: { Accept: "text/html" } });
        if (!resp.ok || /login|signin/i.test(resp.url)) {
          sstate.crawl.msg = "stopped: HTTP " + resp.status;
          break;
        }
        const d = new DOMParser().parseFromString(await resp.text(), "text/html");
        const rows = parseSeasonPlayers(d).rows;
        if (!rows.length) {
          sstate.crawl.msg = "next page has no readable player rows (Yahoo renders it with script?) - page through the list yourself";
          break;
        }
        sstate.crawl.pages++;
        enqueueFa(rows);
        await flushFa();
        for (const l of findSeasonPageLinks(d, next)) if (!visited.has(l) && !queue.includes(l)) queue.push(l);
        renderSeason();
      }
      sls.set({ crawls: { ...crawls, [sig]: Date.now() } });
      if (!sstate.crawl.msg) sstate.crawl.msg = "read " + sstate.crawl.pages + " more page(s)";
    } catch (e) {
      sstate.crawl.msg = "stopped: " + ((e && e.message) || e);
    } finally {
      sstate.crawl.running = false;
      seasonLock.release();
    }
  }

